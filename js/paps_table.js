  /* ---------- 점수 산출 ---------- */
  function toUnits(v, unit) { return Math.round(v / unit); }

  /*
   * 구간을 n등분하여 점수 결정. lo·hi는 단위 정수(포함 범위), base = 첫 점수.
   * 경계 = lo + round(N·k/n) (N = 구간 길이), 반올림(.5 올림)
   */
  function subdividePoint(vU, loU, hiU, n, base, descending) {
    var N = hiU - loU + 1;
    if (N <= 0) return base;
    var k = 0;
    for (var i = 1; i <= n; i++) {
      var b = loU + Math.round(N * i / n);
      if (vU >= b) k = i; else break;
    }
    if (k >= n) k = n - 1;
    return descending ? base - k : base + k;
  }

  /*
   * bands: [[lo,hi] x5] (5등급→1등급). lowerIsBetter면 값·구간 부호를 뒤집어 처리.
   * 반환 { points: 0~20, grade: 1~5 }
   */
  function pointsFromBands(value, bands, unit, lowerIsBetter) {
    if (value === null || value === undefined || isNaN(value) || !bands) return null;
    var sgn = lowerIsBetter ? -1 : 1;
    var b = bands.map(function (r) { return lowerIsBetter ? [-r[1], -r[0]] : [r[0], r[1]]; });
    var vU = toUnits(sgn * value, unit);
    var U = function (x) { return toUnits(x, unit); };
    var min5 = U(b[0][0]), max1 = U(b[4][1]);
    if (vU <= min5) return { points: 0, grade: 5 };
    if (vU >= max1) return { points: 20, grade: 1 };
    var grade;
    if (vU >= U(b[4][0])) grade = 1;
    else if (vU >= U(b[3][0])) grade = 2;
    else if (vU >= U(b[2][0])) grade = 3;
    else if (vU >= U(b[1][0])) grade = 4;
    else grade = 5;
    var pts;
    if (grade === 5) pts = subdividePoint(vU, min5 + 1, U(b[0][1]), 3, 1);
    else if (grade === 4) pts = subdividePoint(vU, U(b[1][0]), U(b[1][1]), 4, 4);
    else if (grade === 3) pts = subdividePoint(vU, U(b[2][0]), U(b[2][1]), 4, 8);
    else if (grade === 2) pts = subdividePoint(vU, U(b[3][0]), U(b[3][1]), 4, 12);
    else pts = subdividePoint(vU, U(b[4][0]), max1 - 1, 4, 16);
    return { points: Math.max(0, Math.min(20, pts)), grade: grade };
  }

  /*
   * BMI 점수: 정상 20점(1등급), 과체중 2등급(15→12), 마름 3등급(11→8),
   * 경도비만 4등급(7→4), 고도비만 5등급(3→1, 36.0 이상 0).
   * ※ 등급은 공식 기준, 등급 내 세부 점수는 별표 5의 등분 규칙을 준용한 추정치.
   */
  function bmiPoints(bmi, gender, gradeKey) {
    var t = BMI[gender] && BMI[gender][gradeKey];
    if (!t || bmi === null || bmi === undefined || isNaN(bmi)) return null;
    var u = 0.1, vU = toUnits(bmi, u), U = function (x) { return toUnits(x, u); };
    if (vU >= U(t.normal[0]) && vU <= U(t.normal[1])) return { points: 20, grade: 1, category: '정상' };
    if (vU <= U(t.thin)) {
      var lo = U(t.thin) - 19; // 마름 구간 폭 2.0 가정
      if (vU < lo) return { points: 8, grade: 3, category: '마름' };
      return { points: subdividePoint(vU, lo, U(t.thin), 4, 8), grade: 3, category: '마름' };
    }
    if (t.over && vU >= U(t.over[0]) && vU <= U(t.over[1])) {
      return { points: subdividePoint(vU, U(t.over[0]), U(t.over[1]), 4, 15, true), grade: 2, category: '과체중' };
    }
    if (vU >= U(t.mild[0]) && vU <= U(t.mild[1])) {
      return { points: subdividePoint(vU, U(t.mild[0]), U(t.mild[1]), 4, 7, true), grade: 4, category: '경도비만' };
    }
    if (vU >= U(t.severe)) {
      if (vU >= U(t.severe) + 60) return { points: 0, grade: 5, category: '고도비만' };
      return { points: subdividePoint(vU, U(t.severe), U(t.severe) + 59, 3, 3, true), grade: 5, category: '고도비만' };
    }
    /* 구간 사이 틈(반올림)은 가까운 쪽으로 */
    return { points: 20, grade: 1, category: '정상' };
  }

  function itemPoints(itemKey, value, gender, gradeKey) {
    if (itemKey === 'bmi') return bmiPoints(value, gender, gradeKey);
    var meta = ITEMS[itemKey];
    var bands = BANDS[gender] && BANDS[gender][itemKey] && BANDS[gender][itemKey][gradeKey];
    if (!meta || !bands) return null;
    return pointsFromBands(value, bands, meta.unit, !!meta.lowerIsBetter);
  }

